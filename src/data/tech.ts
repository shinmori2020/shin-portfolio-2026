// /tech ページの内容。他ページと同じく CMS を使わず型付きで直書きする。
//
// 読み手が3種類（制作会社 / 採用担当 / 技術面接官）いるため 上から下へ段階的に深くする。
// 数字は必ず実測値を書く。「配慮しました」で終わらせない。
// 文体: 読点「、」を使わない（サイト全体の規約）。専門用語には括弧で一言を添える。

export interface TechItem {
  /** 領域（Framework / Language …） */
  cat: string;
  /** 採用したもの。バージョンまで書き いつ時点の判断か分かるようにする */
  name: string;
  /** 何のために使っているか */
  why: string;
}

export interface Decision {
  title: string;
  body: string;
}

export interface CareItem {
  /** 観点（表示速度 / アクセシビリティ …） */
  label: string;
  /** 具体策。抽象論にしない */
  points: string[];
}

export interface Trouble {
  title: string;
  /** 症状 → 原因 → 対処 の3段で書く */
  symptom: string;
  cause: string;
  fix: string;
  /** 詳細な検証記録への導線（GitHub の docs/） */
  docHref?: string;
  docLabel?: string;
}

export interface Skipped {
  title: string;
  body: string;
}

export interface Metric {
  label: string;
  before?: string;
  after: string;
  note?: string;
}

